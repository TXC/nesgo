func (s *ROMTestSuite) TestPrgBanks() {
	r := s.Require()
	buf := make([]byte, 16+(16*1024)-1)

	copy(buf, []byte{
		0x4e, 0x45, 0x53, 0x1a,
		0x01, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
	})

	_, err := NewROMFile(buf)
	r.Error(err)

	buf = make([]byte, 16+(16*1024))

	copy(buf, []byte{
		0x4e, 0x45, 0x53, 0x1a,
		0x01, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
	})

	n := 16 + (16 * 1024)

	for i := 16; i < n; i++ {
		switch i {
		case 16, n - 1:
			buf[i] = 0xee
		default:
			buf[i] = 0xff
		}
	}

	rom, err := NewROMFile(buf)

	r.NoError(err)

	s.Equal(uint16(0x01), rom.PRGBanks)

	n = (16 * 1024)

	for i := 0; i < n; i++ {
		var val uint8

		switch i {
		case 0, n - 1:
			val = 0xee
		default:
			val = 0xff
		}

		s.Equal(val, rom.ROMBanks[0][i])
	}
}

