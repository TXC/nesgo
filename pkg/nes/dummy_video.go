type DummyVideo struct {
	input         chan []uint8
	width, height int
	palette       []color.RGBA
	events        chan Event
	framePool     *sync.Pool
	overscan      bool
	caption       string
	fps           float64
}

func NewVideo(caption string, events chan Event, framePool *sync.Pool, fps float64) (video *DummyVideo, err error) {
	video = &DummyVideo{
		input:     make(chan []uint8, 128),
		palette:   DummyPalette,
		events:    events,
		framePool: framePool,
		overscan:  true,
		caption:   caption,
		fps:       fps,
	}

	return
}

func (video *DummyVideo) Input() chan []uint8 {
	return video.input
}
func (video *DummyVideo) Events() chan Event {
	return video.events
}
func (video *DummyVideo) Run() {
	running := true
	frame := make([]uint32, 0xf000)

	for running {
		select {
		case fb := <-video.input:
			index := 0
			x, y := 0, 0

			for _, c := range fb {
				if pixelInFrame(x, y, video.overscan) {
					p := video.palette[c]
					frame[index] = (uint32(p.R) << 24) | (uint32(p.G) << 16) | (uint32(p.B) << 8) | uint32(p.A)
					index++
				}

				switch x {
				case 255:
					x = 0
					y++
				default:
					x++
				}
			}
			video.framePool.Put(fb)
		default:
			running = false
		}
	}

}
func (video *DummyVideo) SetCaption(caption string) {
	video.caption = caption
}
