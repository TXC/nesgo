func (s *oamTest) TestDisableReads() {
	s.oam.Buffer.Store(0, 0xff)

	s.Equal(uint8(0xff), s.oam.Buffer.Fetch(0))

	s.oam.Buffer.Store(0, 0x00)

	s.Equal(uint8(0x00), s.oam.Buffer.Fetch(0))

	s.oam.Buffer.DisableReads = true

	s.Equal(uint8(0xff), s.oam.Buffer.Fetch(0))

	s.oam.Buffer.DisableReads = false

	s.Equal(uint8(0x00), s.oam.Buffer.Fetch(0))
}

