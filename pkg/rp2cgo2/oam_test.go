func (s *oamTest) TestOAMSprite() {
	address := uint16(0)

	address = 0x0000

	s.oam.Buffer.Store(address+0, 0x00)
	s.oam.Buffer.Store(address+1, 0x01)
	s.oam.Buffer.Store(address+2, 0x02)
	s.oam.Buffer.Store(address+3, 0x03)

	s.Equal(uint32(0x00010203), s.oam.Sprite(0))

	address = 0x0004

	s.oam.Buffer.Store(address+0, 0x04)
	s.oam.Buffer.Store(address+1, 0x05)
	s.oam.Buffer.Store(address+2, 0x06)
	s.oam.Buffer.Store(address+3, 0x07)

	s.Equal(uint32(0x04050607), s.oam.Sprite(1))

	address = 0x001c

	s.oam.Buffer.Store(address+0, 0xfc)
	s.oam.Buffer.Store(address+1, 0xfd)
	s.oam.Buffer.Store(address+2, 0xfe)
	s.oam.Buffer.Store(address+3, 0xff)

	s.Equal(uint32(0xfcfdfeff), s.oam.Sprite(7))
}
