func (s *oamTest) TestClearOAMBuffer() {
	for i := uint16(0); i < 256; i++ {
		s.oam.BasicMemory.Store(i, 0x00)
	}

	for i := uint16(0); i < 32; i++ {
		s.oam.Buffer.Store(i, 0x00)
	}

	scanline := uint16(0)
	cycle := uint16(0)
	size := uint16(8)

	for cycle = 1; cycle <= 64; cycle++ {
		s.oam.SpriteEvaluation(scanline, cycle, size)
	}

	for i := uint16(0); i < 32; i++ {
		s.Equal(uint8(0xff), s.oam.Buffer.Fetch(i))
	}
}

